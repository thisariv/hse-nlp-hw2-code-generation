def extract(name, definitions, header, target):
    source = (SRC/name).read_text()
    lines = source.splitlines(keepends=True)
    tree = ast.parse(source)
    chunks = []
    for definition in definitions:
        node = next(n for n in tree.body if getattr(n, 'name', None) == definition)
        lo = min([node.lineno]+[d.lineno for d in getattr(node, 'decorator_list', [])])-1
        chunks.append(''.join(lines[lo:node.end_lineno]))
    generated = '# Generated by build_final_inference.py from '+name+'; do not edit.\n'+header+'\n\n'+'\n\n'.join(chunks)+'\n'
    (SRC/target).write_text(generated)
    return {'source': name, 'source_sha256': hashlib.sha256(source.encode()).hexdigest(),
            'definitions': definitions, 'generated_sha256': hashlib.sha256(generated.encode()).hexdigest()}


